#!/usr/bin/env python3
"""Character-canvas drawer for the C4 terminal-format diagrams in docs/architecture/.

Each `c4-*.py` file beside this one is the *source* for one `*.terminal.md` embed; the
embed is regenerated by `render.py` and must never be hand-edited. See
`docs/architecture/AGENTS.md` for why the terminal format is drawn this way instead of
through the `draw-visual` skill.

Conventions enforced here:

* Solid borders (`─ │`) mean "built today"; dashed borders (`┄ ┆`) mean "(planned)".
* The outer boundary frame uses `╭ ╌ ╎ ╰` so it never reads as a container.
* Every rendered line is asserted to fit `limit` columns, so a diagram cannot silently
  grow wider than a terminal.
"""


class Canvas:
    def __init__(self, width=72, height=60):
        self.w = width
        self.h = height
        self.g = [[" "] * width for _ in range(height)]

    # --- primitives ---------------------------------------------------
    def put(self, r, c, text):
        assert 0 <= r < self.h, f"row {r} out of range"
        assert 0 <= c + len(text) <= self.w, f"col {c}+{len(text)} out of range: {text!r}"
        for i, ch in enumerate(text):
            self.g[r][c + i] = ch

    def box(self, r, c, w, lines, planned=False, top=(), bottom=(), left=(), right=()):
        """Draw a box at (r, c) of width w. Connector offsets are relative to the box.

        Returns the row index of the box's bottom border.
        """
        h = "┄" if planned else "─"
        v = "┆" if planned else "│"
        field = w - 4
        border = ["┌"] + [h] * (w - 2) + ["┐"]
        for off in top:
            border[off] = "┬"
        self.put(r, c, "".join(border))
        for i, text in enumerate(lines):
            assert len(text) <= field, f"label is {len(text)} > {field} cols: {text!r}"
            self.put(r + 1 + i, c, v + " " + text.ljust(field) + " " + v)
        for off in left:
            self.g[r + off][c] = "┤"
        for off in right:
            self.g[r + off][c + w - 1] = "├"
        border = ["└"] + [h] * (w - 2) + ["┘"]
        for off in bottom:
            border[off] = "┬"
        self.put(r + 1 + len(lines), c, "".join(border))
        return r + 1 + len(lines)

    # --- connectors ---------------------------------------------------
    def down(self, r, c, label=None, rows=2):
        """Arrow pointing down: shaft from row r, arrowhead on row r + rows - 1."""
        for i in range(rows - 1):
            self.g[r + i][c] = "│"
        self.g[r + rows - 1][c] = "▼"
        if label:
            self.put(r, c + 2, label)
        return r + rows

    def up(self, r, c, label=None, rows=2):
        """Arrow pointing up: arrowhead on row r, shaft below it."""
        self.g[r][c] = "▲"
        for i in range(1, rows):
            self.g[r + i][c] = "│"
        if label:
            self.put(r, c + 2, label)
        return r + rows

    def right(self, r, c0, c1, label=""):
        """Arrow pointing right from c0 to an arrowhead at c1."""
        span = c1 - c0
        self.put(r, c0, label.center(span, "─") if label else "─" * span)
        self.g[r][c1] = "►"

    def channel(self, r0, r1, c):
        """A vertical routing line occupying rows r0..r1 - 1."""
        for r in range(r0, r1):
            self.g[r][c] = "│"

    def tap(self, r, c, to_c, label=None, last=False):
        """Branch right out of a routing channel at column c into an arrowhead at to_c."""
        self.g[r][c] = "└" if last else "├"
        self.put(r, c + 1, "─" * (to_c - c - 1))
        self.g[r][to_c] = "►"
        if label:
            self.put(r - 1, c + 1, label)

    # --- boundary -----------------------------------------------------
    def frame(self, r0, c0, r1, c1, title):
        fill = c1 - c0 - 4 - len(title)
        assert fill >= 0, f"frame title too long by {-fill}"
        self.put(r0, c0, "╭╌ " + title + " " + "╌" * fill + "╮")
        for r in range(r0 + 1, r1):
            self.g[r][c0] = "╎"
            self.g[r][c1] = "╎"
        self.put(r1, c0, "╰" + "╌" * (c1 - c0 - 1) + "╯")

    # --- output -------------------------------------------------------
    def render(self, limit=72):
        out = ["".join(row).rstrip() for row in self.g]
        while out and out[-1] == "":
            out.pop()
        for i, line in enumerate(out):
            assert len(line) <= limit, f"line {i} is {len(line)} cols (limit {limit})"
        return "\n".join(out)
