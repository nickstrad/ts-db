/**
 * Property tests for `core/logging/rotation.ts` (plan item 12, work 5): the five retention invariants of
 * item 06 over arbitrary file sets, policies and `now`, plus idempotence (item 06's acceptance criterion).
 *
 * File sets are generated *relative to `now`* as (day offset, hour, role, pid, seq, bytes), so the test
 * knows each directory's true age without calling the module's own date arithmetic. Paths come from
 * `currentPath`, and the generator asserts the bucket it computed independently appears in that path.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import fc from "fast-check";
import { currentPath, type FileEntry, plan, type RotationPolicy } from "../../core/logging/rotation.ts";
import { check, SEED, titled } from "./arbitraries.ts";

const ROLES = ["server", "reader", "restore", "cli"] as const;
const pad = (n: number): string => String(n).padStart(2, "0");
/** Local `YYYY-MM-DD`, written here independently of the module under test. */
const bucket = (d: Date): string => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

const nowArb = fc.date({ min: new Date(2020, 0, 1), max: new Date(2035, 0, 1), noInvalidDate: true });

const policyArb: fc.Arbitrary<RotationPolicy> = fc.record({
  keepDays: fc.integer({ min: 0, max: 30 }),
  gzipAfterDays: fc.integer({ min: 0, max: 30 }),
  // Small caps relative to the generated bytes so the cap bites in roughly half the runs.
  maxTotalBytes: fc.integer({ min: 0, max: 1500 }),
  maxFileBytes: fc.integer({ min: 1, max: 1000 }),
});

/** An entry plus the age (in days) of its directory, known by construction. */
type Aged = { entry: FileEntry; age: number; open: boolean };

function entryArb(
  now: Date,
  policy: RotationPolicy,
  age: fc.Arbitrary<number>,
  maxBytes: number,
): fc.Arbitrary<Aged> {
  return fc.record({
    age,
    hour: fc.integer({ min: 0, max: 23 }),
    role: fc.constantFrom(...ROLES),
    pid: fc.integer({ min: 1, max: 99999 }),
    seq: fc.integer({ min: 0, max: 9 }),
    gz: fc.boolean(),
    bytes: fc.integer({ min: 0, max: maxBytes }),
    mtime: fc.date({ noInvalidDate: true }),
  }).map(({ age, hour, role, pid, seq, gz, bytes, mtime }) => {
    const when = new Date(now.getFullYear(), now.getMonth(), now.getDate() - age, hour);
    const dir = bucket(when);
    const base = currentPath(policy, when, role, pid, seq);
    if (!base.includes(`/${dir}/`)) throw new Error(`generator bucket ${dir} disagrees with path ${base}`);
    return { entry: { path: gz ? `${base}.gz` : base, dir, bytes, mtime }, age, open: false };
  });
}

/** Age mix: most files are recent, with a tail past `keepDays` and a little clock-skew into the future. */
const ageArb = fc.oneof(
  { weight: 3, arbitrary: fc.constant(0) },
  { weight: 6, arbitrary: fc.integer({ min: 1, max: 35 }) },
  { weight: 1, arbitrary: fc.integer({ min: -2, max: -1 }) },
);

/**
 * Byte/cap profiles, so the cap boundary (`total == maxTotalBytes`) is generated, not just hoped for:
 * - wide: bytes 0..600 against caps 0..1500, the cap bites in roughly half the runs;
 * - tight: bytes 0..4 against caps 0..20, so totals land exactly on the cap after some pruning;
 * - exact: the cap is set to the total the plan starts with (today plus every directory age alone keeps).
 */
const profileArb = fc.oneof(
  { weight: 2, arbitrary: fc.constant("wide" as const) },
  { weight: 2, arbitrary: fc.constant("tight" as const) },
  { weight: 1, arbitrary: fc.constant("exact" as const) },
);

/** `now`, a policy, the open file (in today's directory), and other files with unique paths. */
const scenarioArb = fc.tuple(nowArb, policyArb, profileArb).chain(([now, base, profile]) => {
  const maxBytes = profile === "tight" ? 4 : 600;
  const policy = profile === "tight" ? { ...base, maxTotalBytes: base.maxTotalBytes % 21 } : base;
  return fc.tuple(
    entryArb(now, policy, fc.constant(0), maxBytes),
    fc.array(entryArb(now, policy, ageArb, maxBytes), { maxLength: 14 }),
  ).map(([open, rest]) => {
    const seen = new Set<string>([open.entry.path]);
    const files: Aged[] = [{ ...open, open: true }];
    for (const f of rest) {
      if (!seen.has(f.entry.path)) {
        seen.add(f.entry.path);
        files.push(f);
      }
    }
    // Today's directory plus every non-today directory younger than keepDays (the ones that stay on disk).
    const onDisk = files.filter((f) => f.age === 0 || f.age < policy.keepDays);
    const final: RotationPolicy = profile === "exact"
      ? { ...policy, maxTotalBytes: onDisk.reduce((n, f) => n + f.entry.bytes, 0) }
      : policy;
    return { now, policy: final, files, entries: files.map((f) => f.entry) };
  });
});

const union = (...lists: readonly (readonly string[])[]): string[] => lists.flat();

test(
  titled("generators: today's dir, the open file, stale dirs, .gz files and cap pressure all occur"),
  () => {
    const runs = fc.sample(scenarioArb, { numRuns: 300, seed: SEED });
    const outcomes = runs.map((s) => ({ s, p: plan(s.entries, s.now, s.policy) }));
    assert.ok(runs.every((s) => s.files[0].open && s.files[0].age === 0));
    assert.ok(runs.some((s) => s.files.some((f) => !f.open && f.age === 0)), "no other file in today's dir");
    assert.ok(outcomes.some(({ p }) => p.gzip.length > 0), "gzip never planned");
    assert.ok(outcomes.some(({ p }) => p.delete.length > 0), "delete never planned");
    assert.ok(runs.some((s) => s.files.some((f) => f.entry.path.endsWith(".gz"))), "no .gz inputs");
    // A cap-driven delete: something deleted that is younger than keepDays and not today's.
    assert.ok(
      outcomes.some(({ s, p }) =>
        s.files.some((f) => f.age > 0 && f.age < s.policy.keepDays && p.delete.includes(f.entry.path))
      ),
      "cap pruning never triggered",
    );
    // The cap boundary: bytes left after pruning equal the cap exactly, with something pruned by the cap...
    const capPruned = ({ s, p }: typeof outcomes[number]) =>
      s.files.some((f) => f.age > 0 && f.age < s.policy.keepDays && p.delete.includes(f.entry.path));
    assert.ok(
      outcomes.some((o) => {
        const left = o.s.entries.filter((e) => !o.p.delete.includes(e.path)).reduce((n, e) => n + e.bytes, 0);
        return capPruned(o) && left === o.s.policy.maxTotalBytes;
      }),
      "cap equality after pruning never generated",
    );
    // ...and the plan's starting total equals the cap with a directory available to (wrongly) prune.
    assert.ok(
      outcomes.some(({ s }) => {
        const onDisk = s.files.filter((f) => f.age === 0 || f.age < s.policy.keepDays);
        const total = onDisk.reduce((n, f) => n + f.entry.bytes, 0);
        return total === s.policy.maxTotalBytes && onDisk.some((f) => f.age !== 0);
      }),
      "initial total == cap never generated",
    );
  },
);

test(titled("invariant 1: today's directory is never gzipped or deleted"), () => {
  check(fc.property(scenarioArb, ({ now, policy, files, entries }) => {
    const p = plan(entries, now, policy);
    for (const f of files.filter((f) => f.age === 0)) {
      assert.ok(!p.gzip.includes(f.entry.path), `${f.entry.path} gzipped`);
      assert.ok(!p.delete.includes(f.entry.path), `${f.entry.path} deleted`);
      assert.ok(p.keep.includes(f.entry.path), `${f.entry.path} not kept`);
    }
  }));
});

test(titled("invariant 2: the currently open file is never in gzip or delete"), () => {
  check(fc.property(scenarioArb, ({ now, policy, files, entries }) => {
    const open = files.find((f) => f.open)!.entry.path;
    const p = plan(entries, now, policy);
    assert.ok(!p.gzip.includes(open) && !p.delete.includes(open));
  }));
});

test(titled("invariant 3: gzip and delete are disjoint"), () => {
  check(fc.property(scenarioArb, ({ now, policy, entries }) => {
    const p = plan(entries, now, policy);
    assert.deepStrictEqual(p.gzip.filter((x) => p.delete.includes(x)), []);
  }));
});

test(titled("invariant 4: gzip + delete + keep is exactly the input set, each path once"), () => {
  check(fc.property(scenarioArb, ({ now, policy, entries }) => {
    const p = plan(entries, now, policy);
    const all = union(p.gzip, p.delete, p.keep);
    assert.equal(all.length, entries.length, "a path appears twice or went missing");
    assert.deepStrictEqual([...all].sort(), entries.map((e) => e.path).sort());
  }));
});

test(
  titled("invariant 5: over the byte cap, whole oldest directories are pruned first and no more than needed"),
  () => {
    check(fc.property(scenarioArb, ({ now, policy, files, entries }) => {
      const p = plan(entries, now, policy);
      const deleted = new Set(p.delete);
      // Non-today directories that age alone does not delete: the only candidates for cap pruning.
      const candidates = new Map<number, { bytes: number; paths: string[] }>();
      for (const f of files) {
        if (f.age === 0 || f.age >= policy.keepDays) continue;
        const dir = candidates.get(f.age) ?? { bytes: 0, paths: [] };
        dir.bytes += f.entry.bytes;
        dir.paths.push(f.entry.path);
        candidates.set(f.age, dir);
      }
      const pruned = [...candidates].filter(([, d]) => d.paths.some((x) => deleted.has(x)));
      const kept = [...candidates].filter(([, d]) => !d.paths.some((x) => deleted.has(x)));
      for (const [age, d] of pruned) {
        assert.ok(d.paths.every((x) => deleted.has(x)), `dir aged ${age} was only partly pruned`);
      }
      // Bytes still on disk after the plan (gzip keeps its bytes; delete frees them).
      const remaining = entries.filter((e) => !deleted.has(e.path)).reduce((n, e) => n + e.bytes, 0);
      // (a) under the cap, or nothing but today's directory is left to prune.
      assert.ok(
        remaining <= policy.maxTotalBytes || kept.length === 0,
        `still ${remaining} > cap with dirs left`,
      );
      // (b) oldest first: every pruned directory is strictly older than every surviving one.
      if (pruned.length && kept.length) {
        assert.ok(
          Math.min(...pruned.map(([a]) => a)) > Math.max(...kept.map(([a]) => a)),
          "pruned out of age order",
        );
      }
      // (c) minimal: putting back the newest pruned directory would exceed the cap again.
      if (pruned.length) {
        const [, newest] = pruned.reduce((a, b) => (b[0] < a[0] ? b : a));
        assert.ok(remaining + newest.bytes > policy.maxTotalBytes, "pruned a directory it did not need to");
      }
    }));
  },
);

test(
  titled("age rules hold when the cap does not bite: old -> delete, aged -> gzip unless .gz, else keep"),
  () => {
    check(fc.property(scenarioArb, ({ now, policy, files, entries }) => {
      const p = plan(entries, now, { ...policy, maxTotalBytes: Number.MAX_SAFE_INTEGER });
      for (const f of files) {
        const path = f.entry.path;
        if (f.age === 0) assert.ok(p.keep.includes(path));
        else if (f.age >= policy.keepDays) {
          assert.ok(p.delete.includes(path), `${path} (age ${f.age}) not deleted`);
        } else if (f.age >= policy.gzipAfterDays && !path.endsWith(".gz")) {
          assert.ok(p.gzip.includes(path));
        } else assert.ok(p.keep.includes(path), `${path} (age ${f.age}) should be kept`);
      }
    }));
  },
);

test(titled("plan is idempotent: applying it and planning again changes nothing"), () => {
  check(fc.property(scenarioArb, ({ now, policy, entries }) => {
    const first = plan(entries, now, policy);
    const after: FileEntry[] = entries
      .filter((e) => !first.delete.includes(e.path))
      .map((e) =>
        first.gzip.includes(e.path) ? { ...e, path: `${e.path}.gz`, bytes: Math.floor(e.bytes / 2) } : e
      );
    const second = plan(after, now, policy);
    assert.deepStrictEqual(second.gzip, []);
    assert.deepStrictEqual(second.delete, []);
  }));
});
